package wrapper;

public class unboxing {
	public static void main(String[] args) {
		//wrapper class object------> primitive data type
		
		//Integer -> int
		Integer b=10;
		int a=b;
		System.out.println(a);
		
		//Byte ->byte
		Byte d=88;
		byte c=d;
		System.out.println(c);
		
		//Short ->short
		Short f =1110;
		short e=f;
		System.out.println(e);
		
		//Long ->long
		Long L =2346L;
		long l=L;
		System.out.println(l);
		
		//Double -> double
		Double dw =0.2;
		double D  =dw;
		System.out.println(D);
		
		//Float ->float
		Float flo =338.6f;
		float f1=flo;
		System.out.println(f1);
		
		//Character ->char
		Character ch='S';
		char A=ch;
		System.out.println(A);
		
		//Boolean ->boolean
		
		Boolean bool =true;
		boolean b1 =bool;
		System.out.println(b1);
		
		
	}
}
