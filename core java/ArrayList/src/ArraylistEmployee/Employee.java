package ArraylistEmployee;

public class Employee {

		private int empid;
	    private String ename;
	    private double salary;

	    public Employee(int empid, String ename, double salary) {
	        this.empid = empid;
	        this.ename = ename;
	        this.salary = salary;
	    }

	    public int getEmpid() {
	        return empid;
	    }

	    public String getEname() {
	        return ename;
	    }

	    public double getSalary() {
	        return salary;
	    }
	}
	
	

